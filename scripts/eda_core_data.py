#!/usr/bin/env python
"""EDA of the Ryan 2012 S. pombe E-MAP (+ PomBase / Costanzo 2016 cross-references).

Requires: build_ryan_pairs.py and build_costanzo_pairs.py outputs in data/processed/.
Writes:   docs/data_inventory.md (all numbers computed here; nothing hardcoded)
          results/eda/ryan_degree_s2_neg.tsv (per-gene negative-interaction degree)
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

ROOT = Path(__file__).resolve().parent.parent
P = ROOT / "data/processed"
RAW = ROOT / "data/raw"
DOC = ROOT / "docs/data_inventory.md"
RES = ROOT / "results/eda"
sys.path.insert(0, str(ROOT))
from src import protocol  # noqa: E402

THR = protocol.threshold()  # label threshold from config/protocol.yaml
POS_THR = 1.8

L = []


def w(s=""):
    L.append(s)


def table(df: pd.DataFrame, floatfmt="{:.3g}"):
    cols = list(df.columns)
    w("| " + " | ".join(map(str, cols)) + " |")
    w("|" + "---|" * len(cols))
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            cells.append(floatfmt.format(v) if isinstance(v, (float, np.floating)) else str(v))
        w("| " + " | ".join(cells) + " |")
    w()


def pct(x):
    return f"{100 * x:.2f}%"


def corr(a, b):
    m = np.isfinite(a) & np.isfinite(b)
    return stats.pearsonr(a[m], b[m])[0], stats.spearmanr(a[m], b[m])[0], int(m.sum())


def main() -> int:
    RES.mkdir(parents=True, exist_ok=True)
    genes = pd.read_csv(P / "ryan_genes.tsv", sep="\t")
    meas = pd.read_parquet(P / "ryan_measurements.parquet")
    pairs = pd.read_parquet(P / "ryan_pairs.parquet")
    pb = pd.read_csv(RAW / "pombase/gene_IDs_names_products.tsv", sep="\t", dtype=str)
    viab = pd.read_csv(RAW / "pombase/FYPOviability.tsv", sep="\t", header=None, names=["gene", "viability"])
    viab = viab.drop_duplicates("gene").set_index("gene").viability
    orth = pd.read_csv(RAW / "pombase/pombe-cerevisiae-orthologs-with-systematic-ids.txt.gz", sep="\t",
                       header=None, names=["pombe", "cer"], dtype=str)
    cpairs = pd.read_parquet(P / "costanzo_pairs.parquet", columns=["orf_a", "orf_b", "eps_mean", "pval_min",
                                                                    "eps_min", "pval_of_min_eps", "n_meas"])

    w("# Data inventory and EDA — core datasets")
    w()
    w("Generated by `scripts/eda_core_data.py` (do not edit by hand; re-run the script). Provenance, "
      "checksums and licences are in `DATA.md`. Processing: `scripts/build_ryan_pairs.py`, "
      "`scripts/build_costanzo_pairs.py`.")
    w()

    # ------------------------------------------------------------------ structure
    w("## 1. Ryan et al. 2012 E-MAP: structure")
    w()
    n_alleles = meas.query_label.nunique()
    q_ids = genes[genes.is_query]
    a_ids = genes[genes.is_array]
    mapped = genes.dropna(subset=["pombase_id"])
    qg = set(mapped[mapped.is_query].pombase_id)
    ag = set(mapped[mapped.is_array].pombase_id)
    s2rows = set(mapped[mapped.in_s2_rows].pombase_id)
    w("- Dataset S1 (unaveraged): **{} query alleles** (rows; NAT-marked) x **{} array strains** (columns; "
      "G418-marked deletion library). Query alleles belong to {} distinct Ryan query IDs -> {} current PomBase "
      "genes.".format(n_alleles, len(a_ids), len(q_ids), len(qg)))
    w("- Dataset S2 (authors' averaged, one value per gene pair, symmetric): {} query genes x {} array genes."
      .format(genes.in_s2_rows.sum(), len(a_ids)))
    w("- Genes that are both query and array: {}; query-only: {}; array-only: {}; total distinct mapped genes: {}."
      .format(len(qg & ag), len(qg - ag), len(ag - qg), len(qg | ag)))
    w()
    ac = meas.drop_duplicates("query_label").allele_class.value_counts().rename_axis("allele class").reset_index(
        name="query alleles")
    w("Query allele classes (from the label suffix; `unlabelled` = plain strain, i.e. the deletion for "
      "non-essential genes; for some essential genes an unlabelled strain co-exists with a DAmP strain):")
    w()
    table(ac)
    multi = genes[genes.n_query_alleles > 1]
    w(f"- Query genes with >1 allele: {len(multi)} (max {genes.n_query_alleles.max()} alleles for one gene).")
    w()

    # ------------------------------------------------------------------ mapping
    w("## 2. Identifier mapping to PomBase (release in DATA.md)")
    w()
    mc = genes.mapping.str.split(":").str[0].value_counts().rename_axis("mapping").reset_index(name="Ryan IDs")
    table(mc)
    bad = genes[genes.mapping != "exact"][["ryan_id", "pombase_id", "mapping", "gene_name", "is_query", "is_array"]]
    w("Non-exact mappings / failures:")
    w()
    table(bad.fillna("-"))
    merged = genes[genes.merged_with_other_ryan_id].sort_values("pombase_id")[["ryan_id", "pombase_id", "is_query",
                                                                                "is_array"]]
    w(f"- Ryan IDs collapsing onto the same current gene (merged/renamed ORFs): {len(merged)} IDs -> "
      f"{merged.pombase_id.nunique()} genes. Their measurements are pooled (mean); pairs flagged "
      f"`involves_merged_id` ({int(pairs.involves_merged_id.sum())} pairs).")
    w(f"- Label gene-name vs current PomBase name/synonym mismatches (after allowing for the dropped '0' "
      f"characters in Ryan labels, e.g. `hsp9` = hsp90): {int((genes.label_name_consistent == False).sum())} "
      "(renames; systematic IDs are authoritative).")
    gt = mapped.drop_duplicates("pombase_id").gene_type.value_counts().rename_axis("PomBase gene_type").reset_index(
        name="Ryan genes")
    table(gt)

    # ------------------------------------------------------------------ pairs / missingness
    w("## 3. Measured pairs and missingness")
    w()
    n_meas = len(meas)
    n_self = int(meas.self_pair.sum())
    possible_s1 = n_alleles * len(a_ids)
    w(f"- S1 individual measurements: {n_meas:,} of {possible_s1:,} query-allele x array cells "
      f"({pct(n_meas / possible_s1)} filled; {pct(1 - n_meas / possible_s1)} missing). Self-pairs "
      f"(gene vs itself): {n_self}.")
    w(f"- Unique unordered gene pairs (current IDs) with any measurement: **{len(pairs):,}**; with an S2 "
      f"value: **{int(pairs.in_s2.sum()):,}**; only measured with non-main alleles (no S2): "
      f"{int((~pairs.in_s2).sum()):,}.")
    w(f"- Pairs measured in both orientations (A-query x B-array and B-query x A-array, main alleles): "
      f"{int(pairs.both_orientations.sum()):,}.")
    nm = pairs.n_meas.value_counts().sort_index()
    w("- Number of main-allele raw measurements per pair: " +
      ", ".join(f"{k}: {v:,}" for k, v in nm.items()))
    per_q = meas.groupby("query_label").s_raw.size()
    w(f"- Measurements per query allele: median {per_q.median():.0f}, min {per_q.min()}, max {per_q.max()} "
      f"(of {len(a_ids)} arrays). Missing cells reflect linkage filtering, failed/noisy strains and "
      "array strains absent from a batch.")
    per_a = meas.groupby("array_ryan_id").s_raw.size()
    w(f"- Measurements per array strain: median {per_a.median():.0f}, min {per_a.min()}, max {per_a.max()} "
      f"(of {n_alleles} query alleles).")
    w()

    # ------------------------------------------------------------------ distribution
    w("## 4. S-score distribution")
    w()
    s2v = pairs.s_score.dropna().values
    rawv = pairs.s_raw_mean.dropna().values
    raw1 = meas.loc[~meas.self_pair, "s_raw"].values
    qs = [0.001, 0.01, 0.05, 0.25, 0.5, 0.75, 0.95, 0.99, 0.999]
    dist = pd.DataFrame({"quantile": qs, "S2 s_score (pairs)": np.quantile(s2v, qs),
                         "raw mean (pairs)": np.quantile(rawv, qs), "raw single measurements": np.quantile(raw1, qs)})
    table(dist)
    rows = []
    for name, v in [("S2 s_score (primary)", s2v), ("raw mean over main alleles", rawv),
                    ("raw individual measurements", raw1)]:
        rows.append(dict(scale=name, n=len(v), mean=float(np.mean(v)), sd=float(np.std(v)),
                         **{"frac S<-2.3": pct(np.mean(v < THR)), "n S<-2.3": int(np.sum(v < THR)),
                            "frac S>1.8": pct(np.mean(v > POS_THR))}))
    table(pd.DataFrame(rows))
    tr = pd.read_csv(P / "ryan_s2_transform.tsv", sep="\t")
    conv = []
    for k, sub in tr.groupby("orientations"):
        npairs = int((pairs.in_s2 & (pairs.both_orientations == (k == 2))).sum())
        conv.append(f"{'both orientations' if k == 2 else 'one orientation'} ({npairs:,} pairs): S2 = -2.3 <-> raw "
                    f"{np.interp(THR, sub.s_score, sub.s_raw_mean):.2f}")
    w("**Scale (PI decision).** S2 (`s_score`) is the authors' pseudo-averaged score (Collins et al. 2006): "
      "for pairs measured in both orientations it is ~ the mean of the two raw orientation scores; for pairs "
      "measured in only one orientation the raw score is shrunk by a global monotone map, because a single "
      "measurement is noisier (verified exactly in `scripts/verify_core_data.py`). Equivalent thresholds: "
      + "; ".join(conv) + ". Applying -2.3 to the raw mean instead roughly doubles the positive rate "
      "(table above). Default used here: S2 (`s_score`) < -2.3.")
    w()
    by_or = pairs[pairs.in_s2].groupby("both_orientations").s_score.apply(lambda v: pct((v < THR).mean()))
    w(f"- Fraction S2 < -2.3: single-orientation pairs {by_or.get(False)}, reciprocal pairs {by_or.get(True)} "
      "(reciprocal pairs are enriched for query genes, i.e. genes chosen as queries, often hubs).")
    w()

    # ------------------------------------------------------------------ degree
    w("## 5. Negative-interaction (S < -2.3) degree per gene (S2 scale, pairs with S2)")
    w()
    p2 = pairs[pairs.in_s2]
    neg = p2[p2.s_score < THR]
    deg = pd.concat([neg.gene_a, neg.gene_b]).value_counts()
    tested = pd.concat([p2.gene_a, p2.gene_b]).value_counts()
    dg = pd.DataFrame({"tested_pairs": tested, "neg_hits": deg}).fillna(0).astype(int)
    dg["hit_rate"] = dg.neg_hits / dg.tested_pairs
    dg["role"] = np.where(dg.index.isin(qg) & dg.index.isin(ag), "query+array",
                          np.where(dg.index.isin(qg), "query", "array"))
    dg["viability"] = dg.index.map(viab)
    dg["gene_name"] = dg.index.map(pb.set_index("gene_systematic_id").gene_name)
    dg.sort_values("neg_hits", ascending=False).to_csv(RES / "ryan_degree_s2_neg.tsv", sep="\t")
    w(f"- Genes with >=1 S2 pair: {len(dg)}; with 0 negative hits: {int((dg.neg_hits == 0).sum())}; "
      f"median hits {dg.neg_hits.median():.0f}, mean {dg.neg_hits.mean():.1f}, max {dg.neg_hits.max()}.")
    qd = dg.neg_hits.quantile([0.5, 0.75, 0.9, 0.95, 0.99]).round(1)
    w("- Hit-count quantiles (50/75/90/95/99%): " + ", ".join(f"{v:g}" for v in qd.values))
    top10 = dg.sort_values("neg_hits", ascending=False)
    top_share = top10.neg_hits.head(int(np.ceil(0.05 * len(dg)))).sum() / (2 * len(neg))
    w(f"- Top 5% of genes by degree account for {pct(top_share)} of negative-hit endpoints (hub-dominated; "
      "relevant to degree-based baselines and gene-held-out splits).")
    byrole = dg.groupby("role").agg(genes=("neg_hits", "size"), median_tested=("tested_pairs", "median"),
                                    median_hits=("neg_hits", "median"), mean_hit_rate=("hit_rate", "mean")).reset_index()
    table(byrole)
    w("Top 15 genes by negative degree:")
    w()
    table(top10.head(15).reset_index().rename(columns={"index": "gene"})[
        ["gene", "gene_name", "role", "viability", "tested_pairs", "neg_hits", "hit_rate"]].fillna("-"))
    hist = np.histogram(dg.neg_hits, bins=[0, 1, 2, 5, 10, 20, 50, 100, 200, 10000])
    w("Degree histogram: " + "; ".join(f"[{a},{b}): {c}" for a, b, c in zip(hist[1][:-1], hist[1][1:], hist[0])))
    w()

    # ------------------------------------------------------------------ replicate agreement
    w("## 6. Replicate / orientation agreement (raw S1 scale)")
    w()
    bo = pairs[pairs.both_orientations]
    r, rho, n = corr(bo.s_raw_ab.values, bo.s_raw_ba.values)
    w(f"- Reciprocal orientations (A-query x B-array vs B-query x A-array; main alleles): Pearson r = {r:.3f}, "
      f"Spearman = {rho:.3f}, n = {n:,} pairs. (Paper Fig. S1A reports r = 0.4 for replicate + marker-swap pairs.)")
    a_neg, b_neg = bo.s_raw_ab < THR, bo.s_raw_ba < THR
    either = (a_neg | b_neg).sum()
    w(f"- Of reciprocal pairs with S<-2.3 in at least one orientation ({either:,}), both orientations agree in "
      f"{pct((a_neg & b_neg).sum() / max(either, 1))}; P(other orientation < -2.3 | one < -2.3) = "
      f"{pct((a_neg & b_neg).sum() / max(a_neg.sum(), 1))} (vs base rate {pct(b_neg.mean())}).")
    # same-gene, different query strains
    mm = meas[~meas.self_pair & meas.query_gene.notna()]
    rows = []
    for g, sub in mm.groupby("query_gene"):
        labs = sub.query_label.unique()
        if len(labs) < 2:
            continue
        piv = sub.pivot_table(index="array_ryan_id", columns="query_label", values="s_raw")
        for i in range(len(labs)):
            for j in range(i + 1, len(labs)):
                a, b = piv[labs[i]].values, piv[labs[j]].values
                m = np.isfinite(a) & np.isfinite(b)
                if m.sum() > 50:
                    ca = sub.drop_duplicates("query_label").set_index("query_label").allele_class
                    kind = "+".join(sorted([ca[labs[i]], ca[labs[j]]]))
                    rows.append(dict(gene=g, kind=kind, r=np.corrcoef(a[m], b[m])[0, 1], n=int(m.sum())))
    ra = pd.DataFrame(rows)
    if len(ra):
        summ = ra.groupby("kind").agg(allele_pairs=("r", "size"), median_r=("r", "median"),
                                      min_r=("r", "min"), max_r=("r", "max")).reset_index()
        w("- Profile correlation between different query strains of the same gene (across shared arrays):")
        w()
        table(summ)
    w()

    # ------------------------------------------------------------------ essentiality
    w("## 7. Essentiality of Ryan genes (PomBase FYPO deletion viability)")
    w()
    rows = []
    for role, ids in [("query genes", qg), ("array genes", ag), ("all Ryan genes", qg | ag),
                      ("S2 query genes", s2rows)]:
        vc = pd.Series([viab.get(g, "no annotation") for g in ids]).value_counts()
        rows.append(dict(set=role, n=len(ids), **vc.to_dict()))
    table(pd.DataFrame(rows).fillna(0))
    dq = genes[genes.is_query & genes.allele_classes.fillna("").str.contains("DAmP")]
    w(f"- Query genes with a DAmP allele: {len(dq)}; of these PomBase-inviable: "
      f"{int((dq.viability == 'inviable').sum())}.")
    ess_arr = mapped[mapped.is_array & (mapped.viability == "inviable")]
    w(f"- Array genes annotated inviable by PomBase today: {ess_arr.pombase_id.nunique()} (array strains are "
      "deletions from the Bioneer haploid library, so these are likely annotation changes, small/partial "
      "deletions or suppressed strains — flag for PI; they are excluded by the non-essential universe filter).")
    w()

    # ------------------------------------------------------------------ universe
    w("## 8. Non-essential protein-coding universe (prediction target)")
    w()
    pc = set(pb.loc[pb.gene_type == "protein coding gene", "gene_systematic_id"])
    v = pd.Series({g: viab.get(g, "no annotation") for g in pc})
    vcount = v.value_counts()
    w("PomBase protein-coding genes by deletion viability: " + ", ".join(f"{k}: {n}" for k, n in vcount.items()) +
      f" (total {len(pc)}).")
    w()
    univ = set(v[v == "viable"].index)
    univ_cd = set(v[v.isin(["viable", "condition-dependent"])].index)
    rows = []
    for name, U in [("viable only (default)", univ), ("viable + condition-dependent", univ_cd)]:
        n = len(U)
        inU = p2[p2.gene_a.isin(U) & p2.gene_b.isin(U)]
        rows.append({"universe": name, "genes": n, "all pairs": f"{n * (n - 1) // 2:,}",
                     "Ryan genes in universe": len((qg | ag) & U),
                     "Ryan S2 pairs in universe": f"{len(inU):,}",
                     "coverage of universe pairs": pct(len(inU) / (n * (n - 1) / 2)),
                     "frac S2<-2.3 in universe": pct((inU.s_score < THR).mean()),
                     "frac raw<-2.3 in universe": pct((inU.s_raw_mean < THR).mean())})
    table(pd.DataFrame(rows))
    unseen = univ - (qg | ag)
    w(f"- Universe genes never measured by Ryan: {len(unseen)} ({pct(len(unseen) / len(univ))}); pairs with "
      f"at least one unseen gene: {pct(1 - (len(univ) - len(unseen)) * (len(univ) - len(unseen) - 1) / (len(univ) * (len(univ) - 1)))} "
      "of the universe -> most target pairs involve genes absent from training.")
    w()

    # ------------------------------------------------------------------ orthologs / Costanzo
    w("## 9. Ortholog coverage and Costanzo 2016 overlap")
    w()
    orth = orth[orth.cer.str.match(r"^Y", na=False)]
    o_by_p = orth.groupby("pombe").cer.apply(set)
    o_by_c = orth.groupby("cer").pombe.apply(set)
    one2one = {p: next(iter(c)) for p, c in o_by_p.items() if len(c) == 1 and len(o_by_c[next(iter(c))]) == 1}
    allr = qg | ag
    w(f"- PomBase curated pombe->cerevisiae ortholog rows: {len(orth):,}; pombe genes with >=1 ortholog: "
      f"{len(o_by_p):,}; 1:1 ortholog pairs: {len(one2one):,}.")
    w(f"- Ryan genes with >=1 cerevisiae ortholog: {len(allr & set(o_by_p.index))} / {len(allr)} "
      f"({pct(len(allr & set(o_by_p.index)) / len(allr))}); with a 1:1 ortholog: {len(allr & set(one2one))}.")
    cer_measured = set(cpairs.orf_a) | set(cpairs.orf_b)
    w(f"- Costanzo 2016 ORF pairs (all files except HSP90, collapsed): {len(cpairs):,}; ORFs: {len(cer_measured):,}.")
    w(f"- Ryan genes with an ortholog that is screened in Costanzo: "
      f"{sum(1 for g in allr if g in o_by_p.index and o_by_p[g] & cer_measured)}.")
    w()
    # map Ryan pairs to cerevisiae ortholog pairs (all combos), mean eps
    cp = cpairs.set_index(["orf_a", "orf_b"])
    pp = p2[p2.gene_a.isin(o_by_p.index) & p2.gene_b.isin(o_by_p.index)].copy()
    rec = []
    for ga, gb in zip(pp.gene_a.values, pp.gene_b.values):
        for ca in o_by_p[ga]:
            for cb in o_by_p[gb]:
                if ca != cb:
                    rec.append((ga, gb, min(ca, cb), max(ca, cb)))
    rec = pd.DataFrame(rec, columns=["gene_a", "gene_b", "orf_a", "orf_b"])
    rec = rec.merge(cpairs, on=["orf_a", "orf_b"], how="inner")
    agg = rec.groupby(["gene_a", "gene_b"]).agg(eps=("eps_mean", "mean"), eps_min=("eps_min", "min"),
                                                pmin=("pval_min", "min"), n_cer_pairs=("eps_mean", "size")).reset_index()
    j = pp.merge(agg, on=["gene_a", "gene_b"], how="inner")
    j["one2one"] = [one2one.get(a) is not None and one2one.get(b) is not None for a, b in zip(j.gene_a, j.gene_b)]
    w(f"- Ryan S2 pairs where both genes have orthologs: {len(pp):,}; of which >=1 ortholog pair measured in "
      f"Costanzo: **{len(j):,}** (1:1-ortholog pairs: {int(j.one2one.sum()):,}).")
    rows = []
    for name, sub in [("all mapped pairs (mean eps over ortholog pairs)", j), ("1:1 orthologs only", j[j.one2one])]:
        r1, rho1, n1 = corr(sub.s_score.values, sub.eps.values)
        r2, rho2, _ = corr(sub.s_raw_mean.values, sub.eps.values)
        cer_neg = (sub.eps < -0.08) & (sub.pmin < 0.05)
        base = (sub.s_score < THR).mean()
        cond = (sub.s_score[cer_neg] < THR).mean() if cer_neg.any() else np.nan
        strong = sub.eps < -0.35
        cond2 = (sub.s_score[strong] < THR).mean() if strong.any() else np.nan
        rows.append({"subset": name, "n": n1, "Pearson(S2,eps)": r1, "Spearman(S2,eps)": rho1,
                     "Pearson(raw,eps)": r2, "P(S2<-2.3)": pct(base),
                     "P(S2<-2.3 | eps<-0.08,p<.05)": pct(cond), "n cer neg": int(cer_neg.sum()),
                     "P(S2<-2.3 | eps<-0.35)": pct(cond2), "n eps<-0.35": int(strong.sum())})
    table(pd.DataFrame(rows))
    w("(eps<-0.08 & p<0.05 = Costanzo 2016 'intermediate' negative cut-off; eps<-0.35 = an ad-hoc strong-negative cut-off "
      "used here only for illustration. Correlations are computed over all overlapping pairs, dominated by near-zero scores.)")
    w()
    DOC.write_text("\n".join(L) + "\n")
    print(f"wrote {DOC}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
